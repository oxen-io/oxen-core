#!/usr/bin/python3

# Generates src/blockchain_db/sqlite/snapshots.cpp: the mainnet rewards snapshot at HEIGHT, which
# RewardsDB::fixup() restores when it rescans the rewards from there.
#
# Usage: mk_sqlite_snapshots.py DB HEIGHT > src/blockchain_db/sqlite/snapshots.cpp
#
# DB is the oxen.db (sqlite backend) or sqlite.db (LMDB backend) of a mainnet node whose rewards are
# known to be correct at HEIGHT; it is only opened read-only.

import sqlite3
import sys

if len(sys.argv) != 3:
    sys.exit(f"Usage: {sys.argv[0]} DB HEIGHT")
db, height = sys.argv[1], int(sys.argv[2])

conn = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
rows = conn.execute(
    """
    SELECT address, amount, payout_offset, lifetime_locked_stakes, lifetime_unlocked_stakes,
        lifetime_liquidated_stakes, lifetime_rewards
    FROM rewards_snapshots
    WHERE height = ?
    ORDER BY address
    """,
    (height,),
).fetchall()
if not rows:
    sys.exit(f"{db} has no rewards snapshot at height {height}")
for r in rows:
    if len(r[0]) != 20:
        sys.exit(f"Unexpected {len(r[0])}-byte address in the snapshot at height {height}")
    if r[2] is not None:
        sys.exit(f"Unexpected payout_offset (an OXEN-era row) in the snapshot at height {height}")


def amount(a):
    return f"{a // 1_000_000_000:7d}'{a % 1_000_000_000:09d}" if a >= 1_000_000_000 else f"{a:17d}"


print(
    f"""// This file is generated by contrib/mk_sqlite_snapshots.py

#include "snapshots.h"

#include <crypto/literals.h>

namespace cryptonote::snapshots {{

using namespace crypto::literals;

const int64_t height = {height};

static constexpr std::initializer_list<BatchedPaymentAccrued> batched_payments_impl{{
        // clang-format off"""
)
for addr, amt, _, locked, unlocked, liquidated, rewards in rows:
    print(
        f'    {{"0x{addr.hex()}"_eth, {amount(amt)}, {amount(locked)}, {amount(unlocked)}, '
        f"{amount(liquidated)}, {amount(rewards)}}},"
    )
print(
    """        // clang-format on
};
const std::span<const BatchedPaymentAccrued> batched_payments{batched_payments_impl};

}  // namespace cryptonote::snapshots"""
)
